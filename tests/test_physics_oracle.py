"""Differential tests against prismarine-physics 1.8.9 traces.

The fixture is generated by ``tools/mineflayer_oracle/physics_traces.js``. Each trace is a scripted
20-tick course on a flat world; the engine must stay within 1e-6 blocks of the Mineflayer oracle at
every tick (the rounding in the fixture is 1e-9).
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path

import pytest

from pyflayer.data import McData
from pyflayer.models import ChunkPos, Vec3
from pyflayer.physics import ControlState, PhysicsEngine, PlayerState
from pyflayer.world import ChunkColumn, World

FIXTURE = Path(__file__).parent / "fixtures" / "physics_oracle.json"
MC = McData.load("1.8.9")
TOLERANCE = 1e-6


def _state_id(name: str, metadata: int = 0) -> int:
    return (MC.blocks[name].id << 4) | metadata


def make_world(
    *, floor: str = "stone", layers: tuple[tuple[str, int, int], ...] = ()
) -> World:
    world = World(MC)
    column = ChunkColumn(ChunkPos(0, 0))
    for x in range(16):
        for z in range(16):
            for y in range(64):
                column.apply_block_in_place(x, y, z, _state_id(floor))
            for name, low, high in layers:
                for y in range(low, high + 1):
                    column.apply_block_in_place(x, y, z, _state_id(name))
    world.apply_chunk(column)
    return world


def controls_for(name: str) -> Callable[[int], ControlState]:
    if name == "walk_flat":
        return lambda _: ControlState(forward=1, yaw=0)
    if name == "sprint_flat":
        return lambda _: ControlState(forward=1, sprint=True, yaw=0)
    if name == "sneak_flat":
        return lambda _: ControlState(forward=1, sneak=True, yaw=0)
    if name == "jump":
        return lambda tick: ControlState(jump=tick == 0, yaw=0)
    if name == "sprint_jump":
        return lambda tick: ControlState(
            forward=1, sprint=True, jump=tick == 0, yaw=0
        )
    return lambda _: ControlState(forward=1, yaw=0)


CASES = {
    "walk_flat": {},
    "sprint_flat": {},
    "sneak_flat": {},
    "jump": {},
    "sprint_jump": {},
    "ice": {"floor": "ice"},
    "slime": {"floor": "slime"},
    "cobweb": {"layers": (("web", 64, 65),)},
    "water": {"layers": (("water", 64, 65),)},
    "lava": {"layers": (("lava", 64, 65),)},
}


@pytest.fixture(scope="module")
def oracle() -> dict[str, list[dict[str, object]]]:
    payload = json.loads(FIXTURE.read_text())
    return {entry["name"]: entry["trace"] for entry in payload["traces"]}


@pytest.mark.parametrize("name", sorted(CASES))
def test_matches_prismarine_physics(
    oracle: dict[str, list[dict[str, object]]], name: str
) -> None:
    world = make_world(**CASES[name])  # type: ignore[arg-type]
    engine = PhysicsEngine()
    state = PlayerState(Vec3(8.5, 64.0, 8.5), on_ground=True)
    controls = controls_for(name)

    max_error = 0.0
    for tick, expected in enumerate(oracle[name]):
        state = engine.step(state, controls(tick), world)
        actual = (state.position.x, state.position.y, state.position.z)
        reference = expected["pos"]
        error = max(abs(a - b) for a, b in zip(actual, reference))  # type: ignore[arg-type]
        max_error = max(max_error, error)
        assert error <= TOLERANCE, f"{name}: tick {tick} position error {error}"

        assert state.on_ground is expected["onGround"], f"{name}: tick {tick} ground"
        assert state.in_water is expected["inWater"], f"{name}: tick {tick} water"
        assert state.in_lava is expected["inLava"], f"{name}: tick {tick} lava"
